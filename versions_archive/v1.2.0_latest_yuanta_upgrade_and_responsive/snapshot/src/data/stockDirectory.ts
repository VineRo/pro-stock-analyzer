/**
 * 智慧中英文公司名稱與代碼雙向搜尋函式
 * 具備字詞歸一化、權重評分排序與全域台股代碼動態兜底機制
 * @param query 使用者輸入（支援代碼、中文名稱、英文名稱、別名關鍵字）
 * @param scope 搜尋範圍：ALL | DOMESTIC (台股) | FOREIGN (美股) | INDICES (大盤) | CRYPTO (虛擬幣)
 */
export function searchStockDirectory(query: string, scope: SearchScope = 'ALL'): DirectoryStock[] {
  const raw = query.trim();
  if (!raw) {
    return STOCK_DIRECTORY.filter((item) => {
      if (scope === 'DOMESTIC' && item.market !== 'TW') return false;
      if (scope === 'FOREIGN' && (item.market === 'TW' || item.market === 'CRYPTO')) return false;
      if (scope === 'INDICES' && !item.isIndex) return false;
      if (scope === 'CRYPTO' && item.market !== 'CRYPTO') return false;
      return true;
    });
  }

  const cleanQuery = raw.replace(/[\s\-_*.,]/g, '').toLowerCase();
  const lowerRaw = raw.toLowerCase();

  const scored: { item: DirectoryStock; score: number }[] = [];

  for (const item of STOCK_DIRECTORY) {
    // 1. 分類範圍過濾
    if (scope === 'DOMESTIC' && item.market !== 'TW') continue;
    if (scope === 'FOREIGN' && (item.market === 'TW' || item.market === 'CRYPTO')) continue;
    if (scope === 'INDICES' && !item.isIndex) continue;
    if (scope === 'CRYPTO' && item.market !== 'CRYPTO') continue;

    const symClean = item.symbol.replace(/[\s\-_*.,]/g, '').toLowerCase();
    const symLower = item.symbol.toLowerCase();
    const nameClean = item.name.replace(/[\s\-_*.,]/g, '').toLowerCase();
    const nameLower = item.name.toLowerCase();

    let score = 0;

    // 2. 匹配代碼 (精確、開頭、包含)
    if (symClean === cleanQuery || symLower === lowerRaw) {
      score = Math.max(score, 100);
    } else if (symClean.startsWith(cleanQuery)) {
      score = Math.max(score, 85);
    } else if (symClean.includes(cleanQuery)) {
      score = Math.max(score, 70);
    }

    // 3. 匹配名稱 (精確、開頭、包含、反向包含)
    if (nameClean === cleanQuery || nameLower === lowerRaw) {
      score = Math.max(score, 98);
    } else if (nameClean.startsWith(cleanQuery)) {
      score = Math.max(score, 92);
    } else if (nameClean.includes(cleanQuery) || cleanQuery.includes(nameClean)) {
      score = Math.max(score, 85);
    }

    // 4. 匹配別名與簡稱 (包含繁體中文、英文、俗稱)
    for (const alias of item.aliases) {
      const aliasClean = alias.replace(/[\s\-_*.,]/g, '').toLowerCase();
      const aliasLower = alias.toLowerCase();
      if (aliasClean === cleanQuery || aliasLower === lowerRaw) {
        score = Math.max(score, 95);
        break;
      } else if (aliasClean.startsWith(cleanQuery)) {
        score = Math.max(score, 80);
      } else if (aliasClean.includes(cleanQuery) || cleanQuery.includes(aliasClean)) {
        score = Math.max(score, 75);
      }
    }

    // 5. 匹配產業板塊
    if (item.sector) {
      const secClean = item.sector.replace(/[\s\-_*.,]/g, '').toLowerCase();
      if (secClean.includes(cleanQuery)) {
        score = Math.max(score, 50);
      }
    }

    if (score > 0) {
      scored.push({ item, score });
    }
  }

  // 依權重評分由高到低排序
  scored.sort((a, b) => b.score - a.score);
  const results = scored.map((s) => s.item);

  // 6. 若輸入為台股 4~5 碼純數字 (例如 '4147' 或 '9999') 且字典內未完全覆蓋
  // 自動生成上市 (.TW) 與上櫃 (.TWO) 的動態選項，保證 100% 可查詢可點擊
  if (/^\d{4,5}[a-z]?$/i.test(raw)) {
    const upper = raw.toUpperCase();
    const hasExactTw = results.some((r) => r.symbol === `${upper}.TW`);
    const hasExactTwo = results.some((r) => r.symbol === `${upper}.TWO`);

    if (!hasExactTw && (scope === 'ALL' || scope === 'DOMESTIC')) {
      results.push({
        symbol: `${upper}.TW`,
        name: `${upper} (台股上市標的)`,
        aliases: [upper, `${upper}.TW`],
        market: 'TW',
        price: 50.0,
        change: 0.0,
        changePercent: 0.0,
        currency: 'TWD',
        sector: '台灣證券交易所 (TWSE)',
      });
    }
    if (!hasExactTwo && (scope === 'ALL' || scope === 'DOMESTIC')) {
      results.push({
        symbol: `${upper}.TWO`,
        name: `${upper} (台股上櫃/櫃買標的)`,
        aliases: [upper, `${upper}.TWO`],
        market: 'TW',
        price: 50.0,
        change: 0.0,
        changePercent: 0.0,
        currency: 'TWD',
        sector: '台灣櫃買中心 (TPEx)',
      });
    }
  }

  return results;
}
