/**
 * 智慧中英文公司名稱與代碼雙向搜尋函式
 * @param query 使用者輸入（支援代碼、中文名稱、英文名稱、別名關鍵字）
 * @param scope 搜尋範圍：ALL | DOMESTIC (台股) | FOREIGN (美股) | INDICES (大盤) | CRYPTO (虛擬幣)
 */
export function searchStockDirectory(query: string, scope: SearchScope = 'ALL'): DirectoryStock[] {
  const trimmed = query.trim().toLowerCase();

  return STOCK_DIRECTORY.filter((item) => {
    // 1. 分類範圍過濾
    if (scope === 'DOMESTIC' && item.market !== 'TW') return false;
    if (scope === 'FOREIGN' && (item.market === 'TW' || item.market === 'CRYPTO')) return false;
    if (scope === 'INDICES' && !item.isIndex) return false;
    if (scope === 'CRYPTO' && item.market !== 'CRYPTO') return false;

    // 若無輸入搜尋字詞，返回該範圍下的所有股票
    if (!trimmed) return true;

    // 2. 匹配代碼 (例如 AAPL, 2330, 2330.TW)
    const matchSymbol = item.symbol.toLowerCase().includes(trimmed);

    // 3. 匹配公司名稱 (例如 蘋果, 台積電, 輝達, 長榮)
    const matchName = item.name.toLowerCase().includes(trimmed);

    // 4. 匹配中英文別名與簡稱 (例如 Apple, iPhone, TSMC, 護國神山, Google, 航海王)
    const matchAlias = item.aliases.some((alias) => alias.toLowerCase().includes(trimmed));

    // 5. 匹配產業板塊 (例如 半導體, 航運, 高股息, 電動車)
    const matchSector = item.sector ? item.sector.toLowerCase().includes(trimmed) : false;

    return matchSymbol || matchName || matchAlias || matchSector;
  });
}
